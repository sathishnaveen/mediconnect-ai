import { useEffect, useRef } from 'react'
import { Link, useSearchParams } from 'react-router-dom'
import { Bot, Info, RefreshCw, ShieldAlert, Trash2, TriangleAlert } from 'lucide-react'
import { useChat } from '../hooks/useChat'
import { useDocumentTitle } from '../hooks/useDocumentTitle'
import { MessageBubble, TypingIndicator } from '../components/chat/MessageBubble'
import { ChatComposer } from '../components/chat/ChatComposer'
import { SuggestionChips } from '../components/chat/SuggestionChips'
import { Alert } from '../components/ui/Alert'
import { Badge } from '../components/ui/Badge'
import { Button } from '../components/ui/Button'
import { medicalDisclaimer, emergencyLine } from '../lib/knowledge'
import type { ChatMode } from '../types'

const modeConfig: Record<ChatMode, { label: string; tone: 'live' | 'demo' | 'warning' | 'neutral' }> = {
  ai: { label: 'Live AI connected', tone: 'live' },
  demo: { label: 'Demo mode - built-in answers', tone: 'demo' },
  offline: { label: 'Offline sample answers', tone: 'warning' },
  unknown: { label: 'Checking AI status...', tone: 'neutral' },
}

export function ChatPage() {
  useDocumentTitle('AI Healthcare Assistant | MediConnect AI')
  const [searchParams] = useSearchParams()
  const { messages, isTyping, error, mode, send, retry, clearChat } = useChat()
  const scrollRef = useRef<HTMLDivElement | null>(null)
  const initialQuestionSent = useRef(false)

  const pendingQuestion = searchParams.get('q')

  useEffect(() => {
    if (!pendingQuestion || initialQuestionSent.current) return
    initialQuestionSent.current = true
    void send(pendingQuestion)
  }, [pendingQuestion, send])

  useEffect(() => {
    const element = scrollRef.current
    if (!element) return
    element.scrollTo({ top: element.scrollHeight, behavior: 'smooth' })
  }, [messages.length, isTyping])

  const showSuggestions = messages.length <= 1 && !isTyping
  const currentMode = modeConfig[mode]

  return (
    <div className="min-h-[calc(100vh-5rem)] bg-slate-50">
      <div className="container-page py-10 sm:py-14">
        <div className="mx-auto w-full max-w-3xl">
          <div className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
            <div>
              <p className="eyebrow">AI healthcare assistant</p>
              <h1 className="mt-4 text-3xl font-extrabold sm:text-4xl">
                Ask anything about the clinic
              </h1>
              <p className="mt-2 text-sm leading-relaxed text-slate-500">
                Get instant answers about services, specialties, opening hours and how to book -
                powered by AI when configured, honest demo answers when not.
              </p>
            </div>

            <div className="flex shrink-0 flex-col items-start gap-2 sm:items-end">
              <Badge tone={currentMode.tone}>
                <span
                  className={`h-1.5 w-1.5 rounded-full ${
                    mode === 'ai'
                      ? 'bg-emerald-500'
                      : mode === 'demo'
                        ? 'bg-amber-500'
                        : mode === 'offline'
                          ? 'bg-orange-500'
                          : 'bg-slate-400'
                  }`}
                  aria-hidden="true"
                />
                {currentMode.label}
              </Badge>
              <Button
                variant="ghost"
                onClick={clearChat}
                disabled={isTyping}
                aria-label="Clear the chat history"
                className="!py-2 text-xs"
              >
                <Trash2 className="h-4 w-4" aria-hidden="true" />
                Clear chat
              </Button>
            </div>
          </div>

          <div className="mt-6 space-y-3">
            <Alert tone="warning" title="Medical disclaimer" role="status">
              {medicalDisclaimer}{' '}
              <span className="font-semibold">{emergencyLine}</span>
            </Alert>

            <Alert tone="info" title="How this chatbot works" role="status">
              If an AI API key is configured on the server, replies are generated by a live AI model
              and labelled <span className="font-semibold">AI-generated</span>. Without a key, every
              reply is clearly labelled{' '}
              <span className="font-semibold">Demo answer (no AI)</span> and comes from a built-in
              FAQ list - never pretend those are model outputs.
            </Alert>
          </div>

          <div className="mt-6 flex h-[32rem] flex-col overflow-hidden rounded-3xl border border-slate-200 bg-white shadow-card sm:h-[36rem]">
            <div className="flex items-center justify-between border-b border-slate-100 bg-white px-4 py-3 sm:px-6">
              <div className="flex items-center gap-2.5">
                <span className="flex h-9 w-9 items-center justify-center rounded-xl bg-gradient-to-br from-brand-600 to-sky-500 text-white">
                  <Bot className="h-4 w-4" aria-hidden="true" />
                </span>
                <div>
                  <p className="text-sm font-bold text-slate-900">MediConnect Assistant</p>
                  <p className="text-xs text-slate-400">Replies in a few seconds</p>
                </div>
              </div>
              <Link to="/book" className="text-xs font-semibold text-brand-600 hover:text-brand-700">
                Book instead
              </Link>
            </div>

            <div
              ref={scrollRef}
              className="chat-scroll flex-1 space-y-5 overflow-y-auto bg-slate-50/60 px-4 py-5 sm:px-6"
              role="log"
              aria-live="polite"
              aria-label="Chat history"
            >
              {messages.map((message) => (
                <MessageBubble key={message.id} message={message} />
              ))}
              {isTyping ? <TypingIndicator /> : null}
            </div>

            {error ? (
              <div className="border-t border-red-100 bg-red-50 px-4 py-3 sm:px-6">
                <div className="flex flex-wrap items-center justify-between gap-3">
                  <p className="inline-flex items-start gap-2 text-xs font-medium text-red-700">
                    <TriangleAlert className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
                    {error}
                  </p>
                  <Button variant="secondary" onClick={() => void retry()} className="!py-1.5 text-xs">
                    <RefreshCw className="h-3.5 w-3.5" aria-hidden="true" />
                    Retry
                  </Button>
                </div>
              </div>
            ) : null}

            {showSuggestions ? (
              <SuggestionChips onSelect={(question) => void send(question)} disabled={isTyping} />
            ) : null}

            <ChatComposer onSend={(text) => void send(text)} disabled={isTyping} />
          </div>

          <div className="mt-5 flex items-start gap-2.5 rounded-2xl border border-slate-200 bg-white p-4 text-xs leading-relaxed text-slate-500">
            <ShieldAlert className="mt-0.5 h-4 w-4 shrink-0 text-amber-500" aria-hidden="true" />
            <p>
              <span className="font-semibold text-slate-700">Scope of this assistant:</span> it can
              answer general healthcare FAQs, clinic services, doctor specialties and appointment
              booking steps. It must not diagnose diseases, prescribe medication or replace a
              medical professional. Chat history is saved only in this browser and can be cleared at
              any time.{' '}
              <Info className="inline h-3.5 w-3.5" aria-hidden="true" />
            </p>
          </div>
        </div>
      </div>
    </div>
  )
}
